// Writes client/src/lib/landing-photos.ts: the landing's own small photo
// manifest, just the photos in lib/landing-photo-set.ts, one compact row each
// (number, size, blur-up placeholder). The full library manifest
// (lib/photos.ts) is ~180 KB; the landing only shows 26 photos, and this
// keeps its first load small on a phone (Part K5).
//
// Used by resize-photos.mjs (`npm run photos`), and on its own to rebuild
// the file from the existing lib/photos.ts without reprocessing any images:
//
//   node scripts/landing-photos.mjs
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const lib = join(dirname(fileURLToPath(import.meta.url)), "..", "client", "src", "lib");

export async function readLandingSet() {
  const src = await readFile(join(lib, "landing-photo-set.ts"), "utf8");
  const m = src.match(/LANDING_PHOTO_SET\s*=\s*\[([\d,\s]+)\]/);
  if (!m) throw new Error("landing-photo-set.ts: LANDING_PHOTO_SET not found");
  return m[1].split(",").map((s) => Number(s.trim())).filter(Boolean);
}

/** entries: the photos.ts entries ({ name, width, height, lqip, variants }). */
export async function writeLandingPhotos(entries, widths) {
  const set = await readLandingSet();
  const byN = new Map(entries.map((e) => [Number(e.name.replace("hero-", "")), e]));
  const missing = set.filter((n) => !byN.has(n));
  if (missing.length) throw new Error(`landing photos missing from the library: hero-${missing.join(", hero-")}`);
  const PREFIX = "data:image/jpeg;base64,";
  const rows = set.map((n) => {
    const e = byN.get(n);
    if (!e.lqip.startsWith(PREFIX)) throw new Error(`hero-${n}: unexpected placeholder format`);
    return `  [${n}, ${e.width}, ${e.height}, "${e.lqip.slice(PREFIX.length)}"],`;
  });
  const source = `// AUTO-GENERATED by scripts/landing-photos.mjs (run by \`npm run photos\`) — do not edit by hand.
// The landing's photos: the ones listed in landing-photo-set.ts, in that order.

import type { Photo } from "./photos";

const WIDTHS = ${JSON.stringify(widths)};

// [hero number, width, height, blur-up placeholder (base64 JPG)]
const ROWS: [number, number, number, string][] = [
${rows.join("\n")}
];

export const landingPhotos: Photo[] = ROWS.map(([n, width, height, lqip]) => {
  const name = \`hero-\${n}\`;
  const variants = WIDTHS.map((w) => ({ width: w, webp: \`/photos/\${name}-\${w}.webp\`, jpg: \`/photos/\${name}-\${w}.jpg\` }));
  return {
    name,
    width,
    height,
    aspectRatio: Math.round((width / height) * 10000) / 10000,
    lqip: \`${PREFIX}\${lqip}\`,
    variants,
    src: \`/photos/\${name}-\${WIDTHS[WIDTHS.length - 1]}.jpg\`,
    srcSet: variants.map((v) => \`\${v.jpg} \${v.width}w\`).join(", "),
    webpSrcSet: variants.map((v) => \`\${v.webp} \${v.width}w\`).join(", "),
  };
});
`;
  await writeFile(join(lib, "landing-photos.ts"), source);
  return set.length;
}

// Run on its own: rebuild from the existing lib/photos.ts.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = await readFile(join(lib, "photos.ts"), "utf8");
  const start = src.indexOf("export const photos: Photo[] = ") + "export const photos: Photo[] = ".length;
  const json = src.slice(start, src.indexOf("\n];", start) + 2);
  const entries = JSON.parse(json);
  const widths = entries[0].variants.map((v) => v.width);
  const n = await writeLandingPhotos(entries, widths);
  console.log(`landing-photos.ts: ${n} photos`);
}
